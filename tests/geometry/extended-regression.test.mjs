import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const source = await readFile(new URL("../../frontend/js/browser/geometry.js", import.meta.url), "utf8");
const { clamp, distance, ramp, point, angle, bounds, signal } = await import("data:text/javascript," + encodeURIComponent(source));
const near = (a, b, epsilon = 1e-10) => assert.ok(Math.abs(a - b) <= epsilon, `Expected ${a} to be near ${b}`);

test("clamp bounds slight negative inputs", () => { assert.equal(clamp(-0.0001), 0); });
test("clamp bounds large negative inputs", () => { assert.equal(clamp(-1000000), 0); });
test("clamp preserves zero", () => { assert.equal(clamp(0), 0); });
test("clamp preserves a small fraction", () => { assert.equal(clamp(0.125), 0.125); });
test("clamp preserves the midpoint", () => { assert.equal(clamp(0.5), 0.5); });
test("clamp preserves an upper interior fraction", () => { assert.equal(clamp(0.999999), 0.999999); });
test("clamp preserves exactly one", () => { assert.equal(clamp(1), 1); });
test("clamp caps a small overflow", () => { assert.equal(clamp(1.001), 1); });
test("clamp caps huge finite values", () => { assert.equal(clamp(1e300), 1); });
test("clamp rejects NaN", () => { assert.equal(clamp(Number.NaN), 0); });
test("clamp rejects positive infinity", () => { assert.equal(clamp(Infinity), 0); });
test("clamp rejects negative infinity", () => { assert.equal(clamp(-Infinity), 0); });
test("distance computes a right triangle hypotenuse", () => { assert.equal(distance([0, 0], [3, 4]), 5); });
test("distance supports negative coordinates", () => { near(distance([-5, -5], [0, 0]), Math.sqrt(50)); });
test("distance supports one dimensional vectors", () => { assert.equal(distance([-3], [7]), 10); });
test("distance supports three dimensional vectors", () => { assert.equal(distance([0, 0, 0], [3, 4, 12]), 13); });
test("distance supports four dimensional vectors", () => { assert.equal(distance([0, 0, 0, 0], [1, 2, 2, 4]), 5); });
test("distance is zero for identical finite vectors", () => { assert.equal(distance([1.5, -2, 7], [1.5, -2, 7]), 0); });
test("distance is symmetric", () => { near(distance([2, -3], [-8, 5]), distance([-8, 5], [2, -3])); });
test("distance is translation invariant", () => { near(distance([2, 1], [5, 9]), distance([102, -199], [105, -191])); });
test("distance rejects dimension mismatch", () => { assert.equal(distance([1, 2], [1, 2, 3]), Infinity); });
test("ramp starts at zero at its lower bound", () => { assert.equal(ramp(10, 10, 20), 0); });
test("ramp ends at one at its upper bound", () => { assert.equal(ramp(20, 10, 20), 1); });
test("ramp interpolates linearly at the midpoint", () => { assert.equal(ramp(15, 10, 20), 0.5); });
test("ramp clamps below its lower bound", () => { assert.equal(ramp(5, 10, 20), 0); });
test("ramp clamps above its upper bound", () => { assert.equal(ramp(25, 10, 20), 1); });
test("ramp interpolates across negative thresholds", () => { assert.equal(ramp(-5, -10, 0), 0.5); });
